export function categoryFromMccCode(n: number): string | null {
  if (n < 1000 || n > 9999 || Number.isNaN(n)) return null;

  const exact = MCC_EXACT[n];
  if (exact) return exact;

  for (const [lo, hi, cat] of MCC_RANGES) {
    if (n >= lo && n <= hi) return cat;
  }

  return null;
}

/**
 * Parse raw MCC string (digits only) and return app category.
 */
export function categoryFromMccString(raw: string): string | null {
  const d = raw.replace(/\D/g, "").padStart(4, "0").slice(-4);
  if (d.length !== 4) return null;
  const n = parseInt(d, 10);
  if (Number.isNaN(n)) return null;
  return categoryFromMccCode(n);
}
